# app/schemas/abdm/discovery.py
from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field


class Identifier(BaseModel):
    type: str = Field(..., description="e.g. MOBILE, MR, NDHM_HEALTH_NUMBER")
    value: str = Field(..., description="Identifier value")


class PatientDiscoveryQuery(BaseModel):
    id: str = Field(..., description="Patient ABHA Address, e.g. aditya@abdm")
    verifiedIdentifiers: List[Identifier] = Field(default_factory=list)
    unverifiedIdentifiers: List[Identifier] = Field(default_factory=list)
    name: Optional[str] = None
    gender: Optional[str] = None
    yearOfBirth: Optional[int] = None


class CareContextDiscoverRequest(BaseModel):
    requestId: UUID = Field(..., description="Unique UUID for this discovery request")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    transactionId: UUID = Field(..., description="Transaction ID across the discovery session")
    patient: PatientDiscoveryQuery
    hipId: Optional[str] = None


class CareContextRepresentation(BaseModel):
    referenceNumber: str = Field(..., description="Study or Encounter UID")
    display: str = Field(..., description="Human-readable label, e.g. USG Pelvis Report")


class PatientDiscoveryRepresentation(BaseModel):
    referenceNumber: str = Field(..., description="Local Patient ID in Medtatvaa / PACS")
    display: str = Field(..., description="Patient Full Name")
    careContexts: List[CareContextRepresentation] = Field(default_factory=list)
    matchedBy: List[str] = Field(default_factory=list, description="e.g. ['ABHA_ADDRESS', 'MOBILE']")


class GatewayResponseReference(BaseModel):
    requestId: UUID = Field(..., description="The requestId of the incoming request")


class ErrorRepresentation(BaseModel):
    code: int
    message: str


class CareContextOnDiscoverPayload(BaseModel):
    requestId: UUID = Field(..., description="New UUID generated by HIP for this callback")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    transactionId: UUID = Field(..., description="Same transactionId from discover request")
    patient: Optional[PatientDiscoveryRepresentation] = None
    resp: GatewayResponseReference
    error: Optional[ErrorRepresentation] = None