# app/schemas/abdm/linking.py
from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field

from app.schemas.abdm.discovery import (
    CareContextRepresentation,
    ErrorRepresentation,
    GatewayResponseReference,
)


class CareContextRef(BaseModel):
    referenceNumber: str = Field(..., description="Care context reference (e.g. study UID)")


class PatientLinkInitQuery(BaseModel):
    id: str = Field(..., description="Patient ABHA Address, e.g. aditya@sbx")
    referenceNumber: str = Field(..., description="Local patient reference ID in Medtatvaa")
    careContexts: List[CareContextRef] = Field(..., min_length=1)


class LinkInitRequest(BaseModel):
    requestId: UUID = Field(..., description="Unique UUID for this init request")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    transactionId: UUID = Field(..., description="Transaction ID across the linking session")
    patient: PatientLinkInitQuery


class LinkAuthMeta(BaseModel):
    communicationMedium: str = Field(default="MOBILE")
    communicationHint: str = Field(default="******9999")
    communicationExpiry: datetime


class LinkReferenceRepresentation(BaseModel):
    referenceNumber: str = Field(..., description="linkRefNumber generated by HIP")
    authenticationType: str = Field(default="MEDIATED", description="DIRECT or MEDIATED")
    meta: LinkAuthMeta


class LinkOnInitPayload(BaseModel):
    requestId: UUID = Field(..., description="New UUID generated by HIP for on-init callback")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    transactionId: UUID = Field(..., description="Same transactionId from init request")
    link: Optional[LinkReferenceRepresentation] = None
    resp: GatewayResponseReference
    error: Optional[ErrorRepresentation] = None


class LinkConfirmationQuery(BaseModel):
    linkRefNumber: str = Field(..., description="The link reference number provided during init")
    token: str = Field(..., description="User-entered OTP token")


class LinkConfirmRequest(BaseModel):
    requestId: UUID = Field(..., description="Unique UUID for this confirm request")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    confirmation: LinkConfirmationQuery


class PatientLinkConfirmRepresentation(BaseModel):
    referenceNumber: str = Field(..., description="Local patient ID")
    display: str = Field(..., description="Patient display name")
    careContexts: List[CareContextRepresentation] = Field(default_factory=list)


class LinkOnConfirmPayload(BaseModel):
    requestId: UUID = Field(..., description="New UUID generated by HIP for on-confirm callback")
    timestamp: datetime = Field(..., description="ISO UTC timestamp")
    patient: Optional[PatientLinkConfirmRepresentation] = None
    resp: GatewayResponseReference
    error: Optional[ErrorRepresentation] = None